using System;
using System.IO;
using System.Threading.Tasks;
using DuetAPI.ObjectModel;
using NUnit.Framework;

namespace SystemTests.Scenarios.Codes.Compensation;

/// <summary>X, Y and Z, homed, with a height map file to load</summary>
internal static class XyzSetup
{
    /// <summary>
    /// A hand-written 5x5 height map in RepRapFirmware's v2 file format: header comment line,
    /// column label line, grid parameter line, then one row of comma-separated heights per Y step.
    /// Every point reads 0.1, so the mesh deviation statistics are mean 0.1, deviation 0
    /// </summary>
    /// <remarks>
    /// Format from HeightMap::SaveToFile and HeightMap::LoadFromFile in
    /// src/RepRapFirmware/src/Movement/BedProbing/Grid.cpp; the header comment prefix is
    /// GridDefinition::HeightMapComment and the label line is HeightMapLabelLines[2]
    /// </remarks>
    internal const string HeightMapCsv = """
        RepRapFirmware height map file v2 generated by SystemTests, min error 0.100, max error 0.100, mean 0.100, deviation 0.000
        axis0,axis1,min0,max0,min1,max1,radius,spacing0,spacing1,num0,num1
        X,Y,20.00,180.00,20.00,180.00,-1.00,40.00,40.00,5,5
        0.100,0.100,0.100,0.100,0.100
        0.100,0.100,0.100,0.100,0.100
        0.100,0.100,0.100,0.100,0.100
        0.100,0.100,0.100,0.100,0.100
        0.100,0.100,0.100,0.100,0.100
        """;

    /// <summary>
    /// X, Y and Z, marked homed so a test can assert a code un-homes them, optionally with
    /// <see cref="HeightMapCsv"/> as the default height map file
    /// </summary>
    internal static Task<Bench> StartXyzAsync(bool withHeightMap = false)
        => Bench.With(Machines.Xyz, Machines.Xyz.Homed)
                .WithSd(sd =>
                {
                    if (withHeightMap)
                    {
                        sd.WriteSys("heightmap.csv", HeightMapCsv);
                    }
                })
                .StartAsync();
}
