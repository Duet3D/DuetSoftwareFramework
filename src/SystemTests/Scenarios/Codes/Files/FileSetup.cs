using System;
using System.Globalization;
using System.IO;
using System.Text.Json;
using System.Text.RegularExpressions;
using System.Threading;
using System.Threading.Tasks;
using DuetAPI;
using DuetAPI.ObjectModel;
using NUnit.Framework;

namespace SystemTests.Scenarios.Codes.Files;

/// <summary>The job files the file scenarios read, and reads of what the codes report</summary>
internal static class FileSetup
{
    /// <summary>
    /// A job file whose header carries the slicer comments both file info parsers understand, so
    /// every parsed field has a known value. The Z move gives the object height: RepRapFirmware
    /// takes it from the highest Z of a G0/G1 in the tail of the file
    /// (FileInfoParser.cpp, the 'G' case of <c>ParseGCodeFile</c>), and it agrees with
    /// layerHeight * numLayers, which is what RepRapFirmware falls back to
    /// (FileInfoParser.cpp <c>ParseFileHeader</c>)
    /// </summary>
    internal const string InfoFile = """
        ; generated by TestSlicer 1.2
        ; layer_height = 0.25
        ;NUM_LAYERS:8
        ; filament used [mm] = 123.4
        ;TIME:3600
        G1 Z2 F300
        G4 P1
        """;

    /// <summary>The physical path of a file on the bench's virtual SD card</summary>
    internal static string Physical(Bench bench, string directory, string name)
        => Path.Combine(bench.Host.Sd.Root, directory, name);

    /// <summary>
    /// How long a code that reports on the job is given. These codes read the file position through
    /// the job processor, so a bound shorter than the default fails the test that asked rather than
    /// holding the suite up for a minute
    /// </summary>
    internal const int ReportTimeoutMs = 15_000;

    /// <summary>The file position and length M27 reports</summary>
    internal static (long Position, long Length) ParsePrintStatus(string reply)
    {
        Match match = Regex.Match(reply, @"SD printing byte (\d+)/(\d+)");
        if (!match.Success)
        {
            throw new AssertionException($"M27 did not report a file position: \"{reply.Trim()}\"");
        }
        return (long.Parse(match.Groups[1].Value, CultureInfo.InvariantCulture),
                long.Parse(match.Groups[2].Value, CultureInfo.InvariantCulture));
    }

    /// <summary>
    /// An object model field as a number, or NaN where the model leaves it null. Reading it as NaN
    /// fails the assertion that wanted a number rather than the test that asked for the field
    /// </summary>
    internal static Task<double> NumberAsync(DcsTestHost host, Func<DuetControlServer.Model.ObjectModel, double?> read)
        => host.ReadModelAsync(model => read(model) ?? double.NaN);

    /// <summary>
    /// The same reading, once the job monitor has published it. The job counters are recomputed on
    /// an interval rather than by the code that feeds them, so a reading taken in the same
    /// millisecond as the reply describes the moment before it
    /// </summary>
    internal static async Task<double> SettledNumberAsync(DcsTestHost host, Func<DuetControlServer.Model.ObjectModel, double?> read, int timeoutMs = 5_000)
    {
        DateTime deadline = DateTime.UtcNow.AddMilliseconds(timeoutMs);
        double value;
        do
        {
            value = await NumberAsync(host, read);
            if (!double.IsNaN(value))
            {
                return value;
            }
            await Task.Delay(50);
        }
        while (DateTime.UtcNow < deadline);
        return value;
    }

    /// <summary>
    /// An expression's text once it reads as expected, or its last reading when it never does. The
    /// fields a finished job leaves behind are written by the job monitor rather than by the code
    /// that stopped the job, so they settle shortly after the reply
    /// </summary>
    internal static async Task<T> SettledValueAsync<T>(DcsTestHost host, Func<DuetControlServer.Model.ObjectModel, T> read, T expected,
                                                      int timeoutMs = 5_000)
    {
        DateTime deadline = DateTime.UtcNow.AddMilliseconds(timeoutMs);
        T value;
        do
        {
            value = await host.ReadModelAsync(read);
            if (Equals(value, expected))
            {
                return value;
            }
            await Task.Delay(50);
        }
        while (DateTime.UtcNow < deadline);
        return value;
    }

    /// <summary>
    /// The JSON object a code answered with. A malformed answer fails as an assertion naming the
    /// code, because every one of these codes answers a machine-readable object
    /// </summary>
    internal static JsonElement ParseJson(string code, string reply)
    {
        try
        {
            return JsonDocument.Parse(reply.Trim()).RootElement.Clone();
        }
        catch (JsonException e)
        {
            throw new AssertionException($"{code} did not answer with valid JSON: \"{reply.Trim()}\" ({e.Message})");
        }
    }
}
