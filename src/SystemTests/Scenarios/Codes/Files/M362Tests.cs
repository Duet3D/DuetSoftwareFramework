using System;
using System.Globalization;
using System.IO;
using System.Text.Json;
using System.Text.RegularExpressions;
using System.Threading;
using System.Threading.Tasks;
using DuetAPI;
using DuetAPI.ObjectModel;
using NUnit.Framework;
using static SystemTests.Scenarios.Codes.Files.FileSetup;

namespace SystemTests.Scenarios.Codes.Files;

/// <summary>M362, a fragment of a file</summary>
[TestFixture]
[GCode("M362")]
public class M362Tests : BenchFixture
{
    /// <summary>The data a fragment or thumbnail answer carries, or null when it carries none</summary>
    private static string? FragmentData(JsonElement root, string key)
        => root.TryGetProperty(key, out JsonElement fragment) && fragment.TryGetProperty("data", out JsonElement data)
            ? data.GetString()
            : null;

    /// <summary>
    /// M36.2 returns a fragment of a file as text
    /// </summary>
    /// <remarks>
    /// GCodes2.cpp case 36 fraction 2 reads "the height map, or another file" through
    /// <c>RepRap::GetFileFragment</c> (RepRap.cpp), which for a fragment that is not a thumbnail
    /// opens the file with <c>OpenSysFile</c>: an unqualified name is therefore looked up in the
    /// system directory, which is where the height map files it is meant for live
    /// </remarks>
    [Category("KnownGap")]
    [Test]
    public async Task M362ReturnsAFileFragment()
    {
        await using Bench bench = await Bench.With(Machines.Xye, JobMacros.Instrumented, Machines.Xye.Homed)
                                             .WithSd(sd => sd.WriteGCode("info.gcode", InfoFile))
                                             .StartAsync();

        string qualified = await bench.Host.ExecuteCodeAsync("M36.2 P\"0:/gcodes/info.gcode\" S0");
        string unqualified = await bench.Host.ExecuteCodeAsync("M36.2 P\"config.g\" S0");

        Assert.Multiple(() =>
        {
            Assert.That(FragmentData(ParseJson("M36.2", qualified), "fragment") ?? string.Empty,
                        Does.Contain("generated by TestSlicer 1.2"),
                        "M36.2 returns the text at the offset it was given (RepRap.cpp GetFileFragment)");
            Assert.That(FragmentData(ParseJson("M36.2 of an unqualified name", unqualified), "fragment") ?? string.Empty,
                        Does.Contain("M953"),
                        "M36.2 resolves an unqualified name in the system directory (RepRap.cpp GetFileFragment, OpenSysFile)");
        });
    }
}
