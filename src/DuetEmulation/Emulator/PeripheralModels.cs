using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;

namespace DuetEmulation.Emulator;

/// <summary>
/// The C# peripheral models Renode compiles when a bench starts. They are combined into one file,
/// which Renode compiles in one go several seconds faster than including them one by one
/// </summary>
public static partial class PeripheralModels
{
    /// <summary>
    /// One file holding the given models (paths relative to Renode/Peripherals), cached in
    /// build/emulation by the hash of their contents
    /// </summary>
    public static string Combine(IEnumerable<string> models)
    {
        List<(string Model, string Source)> sources = [.. models.Distinct().Select(m =>
            (m, File.ReadAllText(Path.Combine(RepositoryPaths.Renode, "Peripherals", m))))];
        string digest = Convert.ToHexStringLower(
            SHA256.HashData(Encoding.UTF8.GetBytes(string.Join('\0', sources.Select(s => s.Model + '\0' + s.Source)))))[..16];
        string target = Path.Combine(RepositoryPaths.Emulation, $"models-{digest}.cs");
        if (File.Exists(target))
        {
            return target;
        }

        SortedSet<string> usings = new(StringComparer.Ordinal);
        StringBuilder bodies = new();
        foreach ((string model, string source) in sources)
        {
            Match ns = NamespacePattern().Match(source);
            if (!ns.Success)
            {
                throw new InvalidDataException($"{model} has no namespace declaration");
            }
            foreach (string line in source[..ns.Index].Split('\n'))
            {
                if (line.StartsWith("using ", StringComparison.Ordinal))
                {
                    usings.Add(line.Trim());
                }
            }
            bodies.Append("// ").Append(model).Append('\n').Append(source[ns.Index..]).Append('\n');
        }

        Directory.CreateDirectory(RepositoryPaths.Emulation);
        string temporary = $"{target}.{Environment.ProcessId}.part";
        File.WriteAllText(temporary,
            "// Generated by DuetEmulation from src/DuetEmulation/Renode/Peripherals\n" +
            string.Join('\n', usings) + "\n\n" + bodies);
        File.Move(temporary, target, overwrite: true);
        return target;
    }

    [GeneratedRegex(@"^namespace ", RegexOptions.Multiline)]
    private static partial Regex NamespacePattern();
}
