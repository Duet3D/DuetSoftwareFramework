using DuetAPI.Utility;
using NUnit.Framework;
using System.Collections.Generic;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace UnitTests.Utility
{
    [TestFixture]
    public class RegexList
    {
        private static readonly JsonSerializerOptions _options = new() { Converters = { new JsonRegexListConverter() } };

        [Test]
        public void ReadsSerializedRegexObjects()
        {
            List<Regex>? filters = JsonSerializer.Deserialize<List<Regex>>("[{\"Pattern\":\"generated by\\\\s+(.+)\",\"Options\":17}]", _options);

            Assert.That(filters, Is.Not.Null);
            Assert.That(filters!.Count, Is.EqualTo(1));
            Assert.That(filters[0].IsMatch("Generated by kiri:moto 4.2"), Is.True);
        }

        [Test]
        public void ReadsPlainPatternsWrittenByNewerVersions()
        {
            List<Regex>? filters = JsonSerializer.Deserialize<List<Regex>>("[\"generated by\\\\s+(.+)\",\"Sliced by\\\\s+(.+)\"]", _options);

            Assert.That(filters, Is.Not.Null);
            Assert.That(filters!.Count, Is.EqualTo(2));
            Assert.That(filters[0].IsMatch("Generated by kiri:moto 4.2"), Is.True);
            Assert.That(filters[0].Options, Is.EqualTo(RegexOptions.IgnoreCase | RegexOptions.Singleline));
            Assert.That(filters[1].IsMatch("Sliced by PrusaSlicer"), Is.True);
        }

        [Test]
        public void ReadsBothFormsInOneList()
        {
            List<Regex>? filters = JsonSerializer.Deserialize<List<Regex>>("[{\"Pattern\":\"layer_height\\\\D+(?<mm>(\\\\d+\\\\.?\\\\d*))\",\"Options\":17},\"Layer height\\\\D+(?<mm>(\\\\d+\\\\.?\\\\d*))\"]", _options);

            Assert.That(filters, Is.Not.Null);
            Assert.That(filters!.Count, Is.EqualTo(2));
            Assert.That(filters[0].Match(" layer_height = 0.25").Groups["mm"].Value, Is.EqualTo("0.25"));
            Assert.That(filters[1].Match("Layer height: 0.3").Groups["mm"].Value, Is.EqualTo("0.3"));
        }

        [Test]
        public void WritesSerializedRegexObjects()
        {
            string json = JsonSerializer.Serialize<List<Regex>>([new Regex("generated by\\s+(.+)", RegexOptions.IgnoreCase | RegexOptions.Singleline)], _options);

            Assert.That(json, Does.Contain("\"Pattern\""));
            Assert.That(json, Does.Contain("\"Options\":17"));
        }
    }
}
